/**
 * IPC 域注册表（架构改造批 4 前置：channel → 所属模块的「接口在哪」查表）。
 *
 * 记账规则：
 *   · status=in-main    → handler 体仍在 electron/main.ts（待拆，账本 count 应 = main.ts 实际数）
 *   · status=in-features → 已拆到 electron/features/<file>（搬走 = 该域通道必须从 main.ts 消失）
 *   · status=shell      → 壳族基础设施（window/dialog/clipboard/fs/theme/notify/external/shell/awake/updates），留在 main 顶层不拆
 *                         （09-22：app 族 8 个通道已整体拆到 features/app-diagnostics.ts，从 shell 族移出）
 *   · count            → 该域 handler 总数（拆分前基线，搬走后不回填 0，账本永远记总量）
 *   · channels         → 已拆域的完整通道清单，供预检守卫【90】校验「搬干净没有」
 *
 * 每拆一个域：把 handler 体搬进 electron/features/<域>.ts 后，改这里 status=in-features、
 * file=features/<域>.ts、channels 填全 —— 预检【90】会盯着 main.ts 里该域通道数必须归零。
 */
export type IpcDomainStatus = "in-main" | "in-features" | "shell";

export interface IpcDomainEntry {
  /** 域前缀（channel 冒号前部分，如 relay / voice） */
  prefix: string;
  /** 该域 handler 总数（拆分前基线） */
  count: number;
  /** 现在在哪：in-main / in-features / shell */
  status: IpcDomainStatus;
  /** 所在文件：in-main|shell → "main.ts"；in-features → "features/<file>.ts" */
  file: string;
  /** 已拆域的完整通道清单（status=in-features 时必填） */
  channels?: string[];
  /** 备注（计划落点 / 拆分注意） */
  note?: string;
}

