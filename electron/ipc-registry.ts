/** 按通道（完整 channel 名）查所属域条目 */
export function domainOf(channel: string): IpcDomainEntry | undefined {
  const prefix = channel.split(":")[0];
  return IPC_DOMAINS.find((d) => d.prefix === prefix);
}

/** 仍在 electron/main.ts 待拆的域（in-main） */
export function domainsStillInMain(): IpcDomainEntry[] {
  return IPC_DOMAINS.filter((d) => d.status === "in-main");
}
