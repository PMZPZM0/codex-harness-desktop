/** 取某版本的要点（没有则 null）。 */
export function whatsNewEntryOf(version: string): WhatsNewEntry | null {
  const key = String(version ?? "").trim();
  if (!key) return null;
  return WHATS_NEW_ENTRIES.find((entry) => entry.version === key) ?? null;
}
