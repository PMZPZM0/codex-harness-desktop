/** 一条要点：`t` 标题 / `d` 细节（可选）。 */
export type WhatsNewItem = {
  t: string;
  d?: string;
};

/** 一个版本的要点。 */
export type WhatsNewEntry = {
  /** 必须与 `package.json` 的 version **逐字一致**（守卫【11r】比对） */
  version: string;
  /** 展示用日期 `YYYY-MM-DD` */
  date: string;
  items: WhatsNewItem[];
};

