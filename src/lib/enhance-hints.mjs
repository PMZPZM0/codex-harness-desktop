/** 增强按钮的提示气泡词库（09-17 用户要求：「词库丰富一点、个性一点」）。
 *
 *  这些句子在用户**用完一轮之后**浮现在按钮上方，点过一次/看完自动消失。
 *  写作口径（四条，改动时请守）：
 *  ① **说清点了会怎样** —— 气泡是功能性提示，不是装饰；纯卖萌会让新手不知道这个紫色的星星是什么。
 *  ② **个性但不油腻** —— 可以有语气和画面感，不谄媚、不使用网络烂梗（「绝绝子」「yyds」这类会很快过时）。
 *  ③ **不承诺效果** —— 它是"帮你把话说清楚"，不是"让你得到更好的答案"。引擎输出质量取决于模型，
 *     写「保证答得更准」是虚假承诺，用户会拿结果来对账。
 *  ④ **短**（09-20 用户：「气泡小一点和文字时间短一点」）—— 每条 ≤16 字，气泡才收得住。
 *
 *  随机策略：整轮随机不重复（见 pickEnhanceHint），避免连续两次看到同一句。
 */
export const ENHANCE_HINTS = [
  // ── 说清「点了会怎样」 ──
  "说得有点潦草？我帮你把要求补全",
  "把话讲清楚，它才答得准",
  "一句话变一段话，要求一个不漏",
  "帮我改成更明确的指令",
  "补上你没说但需要交代的背景",
  // ── 语气轻松、有个性 ──
  "别急，先让我把这句话捋顺",
  "你这句太省字了，我给它加点料",
  "想到什么说什么，剩下的交给我",
  "像跟同事说话那样随意就行",
  "半句话也能开工，先让它完整起来",
  // ── 场景化的（长输入、口语化、带错别字时最贴切） ──
  "口语也能变规范，不用重打一遍",
  "错别字和语气词我来收拾",
  "把「那个东西」换成具体的要求",
  "顺手加上验收标准，省得来回改",
  "把话说全，能少两轮来回",
  // ── 轻微自嘲/克制的幽默 ──
  "我不是魔法，但能让这句话更像话",
  "点一下，省下组织语言的时间",
  "写得乱没关系，方向对就行",
];

/** 取一条提示，避免与上次重复（词库小，用上次值排除即可）。 */
export function pickEnhanceHint(previous) {
  const pool = ENHANCE_HINTS.length > 1 && previous
    ? ENHANCE_HINTS.filter((hint) => hint !== previous)
    : ENHANCE_HINTS;
  return pool[Math.floor(Math.random() * pool.length)];
}

/** 提示的触发条件（**09-20 用户改口径**：「增强弹出来频率太高了，一输入文字就出来了，降低一下频率」）：
 *  ① **第 1 次成功发送后**弹一次。
 *     ⛔ 旧口径是「每次启动后第一次**输入**必弹」（09-17 用户定的）—— 那正是"一输入文字就出来"的
 *     来源：用户刚打开应用、刚开始打字就被提醒，体验像被打断。改成**发送后**：只在用户真用完
 *     一轮、可能想复用时提示，打字期间完全不打扰。
 *  ② 之后每 **10** 次发送弹一次（原 5 次，同样为降频）。
 *  ③ 输入**很长**的需求时弹一次（门槛 50 → **120** 字符），按"编辑会话"节流。
 *
 *  ⛔ 触发只能发生在**按钮可见时**（见 App 侧 `enhanceAnchorVisible`）：气泡挂在增强按钮上方，
 *  按钮没渲染出来就没地方显示。按钮可见 ⇔ 输入框有内容（或还有可还原的原文备份）。
 *  ⛔ 09-23 起可见性**不再看回合运行状态** ⇒「运行中打草稿」现在也会弹提醒，属预期（用户要求）。
 *  ⛔ 条件③ 必须有节流 + 冷却：边打字边弹会变成骚扰（每敲一个字都判定一次），刚弹过又弹同样烦。
 *  所有触发共享一个冷却窗口（见 HINT_COOLDOWN_MS）。
 */

/** 两次提示之间的最小间隔，防止多条触发条件叠加时连弹（09-20：1 分钟 → 3 分钟）。 */
export const HINT_COOLDOWN_MS = 180000;

/** 触发条件：第 n 次**成功发送**后该弹（第 1 次 + 之后每 10 次）。 */
export function shouldShowHintAfterSends(sendCount) {
  return Number.isInteger(sendCount) && sendCount > 0 && (sendCount === 1 || sendCount % 10 === 0);
}

/** 触发条件③：输入长度达到"长需求"门槛（按去掉首尾空白后的字符数算）。 */
export function isLongPrompt(text) {
  return typeof text === "string" && text.trim().length >= 120;
}

/** 气泡自动消失时间（09-20 用户要求调短：6 秒 → 3 秒）。 */
export const HINT_AUTO_HIDE_MS = 3000;
