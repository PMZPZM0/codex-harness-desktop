/** 增强按钮的提示气泡词库（09-17 用户要求：「词库丰富一点、个性一点」）。
 *
 *  这些句子在用户**输入内容后**浮现在按钮上方，点过一次/看完自动消失。
 *  写作口径（三条，改动时请守）：
 *  ① **说清点了会怎样** —— 气泡是功能性提示，不是装饰；纯卖萌会让新手不知道这个紫色的星星是什么。
 *  ② **个性但不油腻** —— 可以有语气和画面感，不谄媚、不使用网络烂梗（「绝绝子」「yyds」这类会很快过时）。
 *  ③ **不承诺效果** —— 它是"帮你把话说清楚"，不是"让你得到更好的答案"。引擎输出质量取决于模型，
 *     写「保证答得更准」是虚假承诺，用户会拿结果来对账。
 *
 *  随机策略：整轮随机不重复（见 pickEnhanceHint），避免连续两次看到同一句。
 */
export const ENHANCE_HINTS = [
  // ── 说清「点了会怎样」 ──
  "说得有点潦草？我帮你把要求补全",
  "把话讲清楚，它才答得准",
  "一句话变一段话，要求一个不漏",
  "帮我改成更明确的指令",
  "补上你没说但需要交代的背景",
  // ── 语气轻松、有个性 ──
  "别急，先让我把这句话捋顺",
  "你这句太省字了，我给它加点料",
  "想到什么说什么，剩下的交给我",
  "像跟同事说话那样随意——我来翻译成需求",
  "半句话也能开工，先让它完整起来",
  // ── 场景化的（长输入、口语化、带错别字时最贴切） ──
  "口语也能变规范，不用重打一遍",
  "错别字和语气词我来收拾",
  "把「那个东西」换成具体的要求",
  "顺手加上验收标准，省得来回改",
  "把话说全，能少两轮来回",
  // ── 轻微自嘲/克制的幽默 ──
  "我不是魔法，但能让这句话更像话",
  "点一下，省下你自己组织语言的时间",
  "写得乱没关系，方向对就行",
];

/** 取一条提示，避免与上次重复（词库小，用上次值排除即可）。 */
export function pickEnhanceHint(previous) {
  const pool = ENHANCE_HINTS.length > 1 && previous
    ? ENHANCE_HINTS.filter((hint) => hint !== previous)
    : ENHANCE_HINTS;
  return pool[Math.floor(Math.random() * pool.length)];
}

/** 每多少次「发送/提交输入」展示一次气泡（用户指定 09-17：每 5 次展示一次）。
 *  计数在渲染层内存里，不落盘 —— 重启后重新数，符合"偶尔提示一下"的定位。 */
export const HINT_EVERY_N_SENDS = 5;

/** 第 n 次发送后是否该展示气泡。
 *  抽成纯函数是为了能离线断言节奏（真发 5 条消息会跑引擎、几分钟且污染会话历史）。 */
export function shouldShowHint(sendCount) {
  return Number.isInteger(sendCount) && sendCount > 0 && sendCount % HINT_EVERY_N_SENDS === 0;
}

/** 气泡自动消失时间（用户指定：约 6 秒）。 */
export const HINT_AUTO_HIDE_MS = 6000;
