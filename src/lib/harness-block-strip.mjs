/**
 * harness 注入块的剥离（显示侧唯一真相源）。
 *
 * 三种形态都要处理：
 *   ① **完整形态**（正常注入）：`[Harness 常驻记忆 · …]` … `[常驻记忆结束]`／
 *      `[Harness 相关记忆，仅供参考]` … `[记忆结束]` —— 成对正则即可。
 *   ② **残缺形态**（09-22 用户截图反馈）：只有头标签、闭合标签丢了。实测 rollout 原文：
 *      `空是因为这个是新会话…\n\n[Harness 常驻记忆 · …]\n## 踩坑与纪律…\n- 2026-09-22 ⚠️ 坑：…`
 *      后直接接召回块。成对正则不命中 ⇒ **整段常驻记忆铺进用户气泡 + 左栏会话标题**（每轮复现）。
 *      来源可能有三：旧版构建的截断、引擎回写、用户复述时丢尾。
 *   ③ **统一记忆（fabric）段**（10-07 用户实测「项目记忆每次消息都展示 + 出现两个用户消息」）：
 *      注入端**刻意不带标记**（守卫【fabric】⑥），而调用方忘了拼 ⇒ 机器文本直接漏进气泡。
 *      按它自己的机器标题整段剥（详见 ③ 处注释）。
 *
 * 残缺剥离的判据（关键是**不误伤用户正文**）：
 *   · 注入块永远拼在用户原话**之后**（send 路径 `…${memoryPrefix}`）；
 *   · 因此从头标签处吃到**串尾**；
 *   · 但仅当标签**后面紧跟注入块特征**（`## 踩坑与纪律` / `# 纪律与记忆` / `> 按分类分节` /
 *     `## 任务经验` 等小节名）时才剥 —— 用户在正文里讨论这些标签（本次反馈就是在讨论它）
 *     不会被吃掉。
 */

/** 头标签（常驻 / 召回两种，描述串用 [^\]]* 吃掉 ⇒ 注入端改措辞不用同步改这里） */
const HEAD = /\[Harness\s*(?:常驻记忆|相关记忆)[^\]]*\]/;

/** 注入块特征：头标签之后紧跟这些内容才认定它是注入块（护栏，防误伤用户正文） */
const BLOCK_HINT = /^\s*(?:#{1,3}\s*(?:踩坑与纪律|项目记忆|用户档案|项目背景|近期工作日志|纪律与记忆)|>\s*按分类分节|##\s*(?:任务经验|用户纠错|用户偏好|工作流))/;

/**
 * 剥掉文本里所有 harness 注入块（完整形态 + 残缺形态）。
 * @param {string} text
 * @returns {string}
 */
export function stripHarnessBlocks(text) {
  if (!text || typeof text !== "string") return text ?? "";

  /* ① 完整形态（成对闭合）—— 先做，让残缺判据不会撞上已闭合的块 */
  let out = text
    /* 闭合标签必须**独立成行**（09-23 自指污染）：L2 纪律行会在正文里字面写出闭合标签，
       非贪婪成对正则会**在它内部提前闭合** ⇒ 只剥前半段、后半段铺进 L4「需求」/L2「现象」，
       并继续喂出新的垃圾行。注入端拼的就是独立一行（memory-layers:705/711、send.tsx:278）。 */
    .replace(/^\[Harness 相关记忆，仅供参考\][\s\S]*?^\[记忆结束\][ \t]*\r?\n?/gm, "")
    .replace(/^\[Harness 常驻记忆[^\]]*\][\s\S]*?^\[常驻记忆结束\][ \t]*\r?\n?/gm, "")
    // 09-23：每轮注入的当前时间块（now-block.mjs）——模型看得见，气泡/标题里必须剥掉
    .replace(/^\[当前时间\][\s\S]*?^\[时间结束\][ \t]*\r?\n?/gm, "");

  /* ② 残缺形态：残留头标签 + 其后是注入块特征 ⇒ 从该标签吃到串尾 */
  const hit = out.match(HEAD);
  if (hit && hit.index !== undefined) {
    const rest = out.slice(hit.index + hit[0].length);
    if (BLOCK_HINT.test(rest)) out = out.slice(0, hit.index);
    /* 头标签后面不像注入块（用户在讨论它）⇒ 原样保留，不吞用户正文 */
  }

  /* ③ 统一记忆（fabric）段 —— 10-05 新增，**注入端刻意不带 [Harness …] 标记**
   *    （memory-fabric.section() 的注释 + 守卫【fabric】⑥ 都写明「标记由调用方拼在整段外面」）。
   *    ⛔⛔ 但两个调用方（渲染层 send 路径 `memoryPrefix += roleCtx.text`、被委派会话
   *        `delegate-memory.ts` 的 `body += "\n\n" + built.text`）**都没拼标记** ⇒
   *        上面 ①/② 两条都看不见它，整段机器文本漏进用户气泡与串标题；
   *        并且 `userMessageMatchesInput` 两侧都过本函数，服务端带 fabric、本地乐观消息不带
   *        ⇒ 文本不相等 ⇒ **乐观气泡永不合并，同一条消息在一轮里显示两遍**
   *        （用户 10-07 实测：「项目记忆每次消息都展示」+「出现两个用户消息」）。
   *    ⛔ 锚点用 `（本次注入 N / 命名空间共 M 条）` 这个 **memory-fabric.section() 独有的机器串**，
   *        而不是 `## 项目记忆` —— 后者在**常驻记忆块里**也有一份同名小节（memory-layers 的
   *        层级标题），只认 `## 项目记忆` 会把用户自己写的同名小节一起吃掉。
   *        机器串里带「本次注入 / 命名空间」这类词，用户不会原样打出来 ⇒ 不误伤正文。
   *    ⛔ 消费方在 `buildContext` 侧补标记后，本条仍要留着：**历史已落盘的消息**与
   *        「标记丢了」的残缺形态都靠它兜底（与 ①/② 的纪律一致：显示侧是容错层）。 */
  out = out.replace(
    /^##\s[^\n]*（本次注入\s*\d+\s*\/\s*命名空间共\s*\d+\s*条）[^\n]*(?:\r?\n(?!\r?\n)[^\n]*)*\r?\n?/gm,
    ""
  );
  return out;
}
