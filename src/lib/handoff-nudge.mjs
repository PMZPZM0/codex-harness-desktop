// src/lib/handoff-nudge.mjs —— 长会话「接班提醒」的指令片段（10-27 用户令）
//
// 用户原话：「不用那么复杂，就在 codex 的个性化指令里面加一条可以吧，让 codex 自主询问」。
// ⇒ 不做回合计数 / 弹窗 / 状态机，只在**每回合下发的 developer instructions** 里加一条行为指令，
//   由模型自己判断「这个会话是不是已经长到该交接了」，并**只问一次**。
//
// 为什么挂在 developer instructions 而不是写进用户的 AGENTS.md：
//   ① 用户的 AGENTS.md 是他自己的文本，程序**不许**偷偷追加（会被下次保存覆盖，也等于篡改用户内容）；
//   ② developer instructions 每回合下发、按会话隔离（thread settings 里持久），随时可改可撤；
//   ③ 与「需求询问」同一套通道（见 reply-style.mjs），一个数组拼接点，不新增机制。
//
// ⛔ 本模块是纯函数（零依赖），便于守卫直接 import 跑真实现。

/** 注入块首行标记（幂等剥离与守卫断言都以它为锚） */
export const HANDOFF_NUDGE_HEADING = "长会话交接提醒（自主询问，只问一次）";

/**
 * 交接提醒指令。
 * ⛔ 三条硬约束不许删：① 大致阈值（40~50 轮或已压缩过）；② **只问一次**、拒绝后不再提；
 *   ③ 同意时走 handoff 技能 + 写 HANDOFF.md（否则模型会自己编一份"摘要"当交接，反而丢信息）。
 */
export function handoffNudge() {
  return [
    `## ${HANDOFF_NUDGE_HEADING}`,
    "- 触发判断由你自己看：本会话已经很长（大约 40~50 轮以上），或者你发现早期细节已被压缩成摘要、开始记不清前面定过的事。",
    "- 触发时用一句话主动问用户：要不要用 **handoff** 技能写一份交接文档，换一个新会话接手继续。",
    "- 只问一次：用户说「继续 / 不用 / 别问」，此后本会话不再提这件事。",
    "- 用户同意时调用 **handoff** 技能，把交接文档写到仓库根的 `HANDOFF.md`（在做什么 / 已完成 / 卡在哪 / 下一步 / 坑），再提示用户新开会话、先读这份文档。",
    "- 这一条只影响「何时提醒交接」，不改变结论与代码质量，也不要在普通短会话里提它。",
  ].join("\n");
}
